for (const [path, def] of Object.entries(defs)) {
  const extra = { ...def.extra };
  if (def.numberPrefix)
    extra.number = {
      type: String,
      unique: true,
      sparse: true,
      immutable: true,
    };
  for (const [key, fields] of Object.entries(def.arrays || {})) {
    const schema = {};
    for (const [field, spec] of Object.entries(fields))
      schema[field] = {
        type: spec.type === "number" ? Number : String,
        required: !!spec.required,
        default: spec.type === "number" ? 0 : "",
      };
    extra[key] = [new mongoose.Schema(schema, { _id: false })];
  }
  const Model = createModel(
    `Studio${path
      .split("-")
      .map((s) => s[0].toUpperCase() + s.slice(1))
      .join("")}`,
    def.fields,
    def.defaults || {},
    extra,
  );
  Model.schema.index({ ownerUserId: 1, archived: 1 });
  if (def.fields.slug) Model.schema.index({ slug: 1 }, { unique: true });
  businessModels[path] = Model;
  businessModules[path] = {
    Model,
    fields: def.fields,
    title: def.name,
    status: def.fields.status ? "status" : undefined,
    permission: def.permission,
    displayTitle: def.title,
    singular: def.singular,
    defaults: def.defaults || {},
    arrays: def.arrays,
    numberPrefix: def.numberPrefix,
    filters: [
      "platform",
      "clientId",
      "projectId",
      "employeeId",
      "status",
    ].filter((k) => def.fields[k]),
  };
}

